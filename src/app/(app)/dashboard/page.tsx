import Link from "next/link";
import { requireRole } from "@/server/auth";
import { ownerDashboard } from "@/server/services/dashboard";
import { hasRole } from "@/server/ctx";
import { PageHead, StatusBadge, fmtDate, Empty } from "@/components/ui";
import { RecommendationActions } from "@/components/GovernanceClient";
import { ScanButton } from "./ScanButton";

export const dynamic = "force-dynamic";
export const metadata = { title: "Owners & reviews" };

export default async function Dashboard() {
  const ctx = await requireRole("PROCESS_OWNER", "ADMIN", "PUBLISHER", "AUDITOR");
  const d = await ownerDashboard(ctx);
  return (
    <>
      <PageHead title="Owners & review dates" sub={hasRole(ctx, "ADMIN", "PUBLISHER", "AUDITOR") ? "All guides in your scope" : "Guides you own or back up"}>
        {hasRole(ctx, "ADMIN", "PUBLISHER", "PROCESS_OWNER") ? <ScanButton /> : null}
      </PageHead>
      <div className="grid cols-3">
        <div className="card"><div className="stat">{d.rows.filter((r) => r.live).length}</div><div>published guides</div></div>
        <div className="card"><div className="stat" style={{ color: d.overdue.length ? "var(--danger)" : undefined }}>{d.overdue.length}</div><div>overdue for review</div></div>
        <div className="card"><div className="stat">{d.dueSoon.length}</div><div>due within 30 days</div></div>
        <div className="card"><div className="stat" style={{ color: d.orphaned.length ? "var(--danger)" : undefined }}>{d.orphaned.length}</div><div>orphaned (owner inactive)</div></div>
        <div className="card"><div className="stat">{d.recommendations.length}</div><div>open review recommendations</div></div>
      </div>
      {d.recommendations.length ? (
        <section className="card" style={{ marginTop: 16 }} aria-labelledby="rec-h"><h2 id="rec-h">Review recommendations</h2>
          <p className="muted">Generated by health checks. They never change approved content; accepting one marks the guide “under review”.</p>
          <ul style={{ listStyle: "none", padding: 0, display: "grid", gap: 10 }}>
            {d.recommendations.map((r) => (
              <li key={r.id}><Link href={`/guides/${r.guideId}`}>{r.guide.documentId} · {r.guide.title}</Link> <span className="badge warn">{r.source.replaceAll("_", " ").toLowerCase()}</span><br />{(r.reasons as { message: string }[]).map((x) => x.message).join("; ")}<br /><RecommendationActions id={r.id} /></li>
            ))}
          </ul>
        </section>
      ) : null}
      <section style={{ marginTop: 16 }} aria-labelledby="all-h"><h2 id="all-h">Guides</h2>
        {d.rows.length === 0 ? <Empty>No guides.</Empty> : (
          <div className="table-wrap"><table className="table"><thead><tr><th scope="col">Guide</th><th scope="col">Status</th><th scope="col">Owner</th><th scope="col">Backup</th><th scope="col">Review due</th><th scope="col">Flags</th></tr></thead><tbody>
            {d.rows.map((r) => (
              <tr key={r.id}><td><Link href={`/guides/${r.id}`}>{r.documentId} · {r.title}</Link></td><td><StatusBadge status={r.status} /></td>
                <td>{r.ownerName ?? "unassigned"}{r.ownerName && !r.ownerActive ? <span className="badge danger" style={{ marginLeft: 6 }}>inactive</span> : null}</td><td>{r.backupName ?? "—"}</td>
                <td>{fmtDate(r.reviewDate)}{r.daysToReview !== null ? <span className={r.daysToReview < 0 ? "conf-low" : "muted"}> ({r.daysToReview < 0 ? `${-r.daysToReview} days overdue` : `in ${r.daysToReview} days`})</span> : null}</td>
                <td>{r.orphaned ? <span className="badge danger">orphaned</span> : null} {r.openRecs.length ? <span className="badge warn">{r.openRecs.length} recommendation(s)</span> : null}</td></tr>
            ))}
          </tbody></table></div>
        )}
      </section>
    </>
  );
}
