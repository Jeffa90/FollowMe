import Link from "next/link";
import { notFound } from "next/navigation";
import { requireCtx } from "@/server/auth";
import { hasRole } from "@/server/ctx";
import { prisma } from "@/server/db";
import { listVersions, loadGuide, getVersionDetail } from "@/server/services/guides";
import { assess, runHealth } from "@/server/services/health";
import { listFeedback, liveUrl } from "@/server/services/library";
import { canEditContent, isOwnerOrAdmin, canReadVersion } from "@/server/authz";
import { OPEN_STATUSES, type GuideStatus } from "@/lib/roles";
import { PageHead, SeverityBadge, StatusBadge, fmtDate, fmtDateTime } from "@/components/ui";
import { CompareForm, FeedbackActions, FindingActions, MetadataForm, RecommendationActions, ReconcileForm, WorkflowActions, type Perm } from "@/components/GovernanceClient";

export const dynamic = "force-dynamic";
export const metadata = { title: "Guide governance" };

export default async function GuideGovernance({ params }: { params: Promise<{ id: string }> }) {
  const ctx = await requireCtx();
  const { id } = await params;
  const guide = await loadGuide(ctx, id).catch(() => null);
  if (!guide) notFound();
  const versions = await listVersions(ctx, guide.id);
  const working = await prisma.guideVersion.findFirst({ where: { guideId: guide.id, status: { in: OPEN_STATUSES } }, orderBy: { number: "desc" } });
  const workingD = working && canReadVersion(ctx, guide, working.status as GuideStatus) ? await getVersionDetail(ctx, working.id) : null;
  const live = guide.liveVersionId ? await prisma.guideVersion.findUnique({ where: { id: guide.liveVersionId } }) : null;
  const subject = workingD ?? live;
  const findings = subject && canReadVersion(ctx, guide, subject.status as GuideStatus) ? await runHealth(ctx.orgId, subject.id) : [];
  const assessment = assess(findings);
  const [users, sites, workflows, recs, decisions, tpl] = await Promise.all([
    prisma.user.findMany({ where: { orgId: ctx.orgId, active: true }, select: { id: true, name: true, roles: true }, orderBy: { name: "asc" } }),
    prisma.site.findMany({ where: { orgId: ctx.orgId } }),
    prisma.workflow.findMany({ where: { orgId: ctx.orgId } }),
    prisma.reviewRecommendation.findMany({ where: { guideId: guide.id, status: "OPEN" }, orderBy: { createdAt: "desc" } }),
    working ? prisma.approvalDecision.findMany({ where: { versionId: working.id }, orderBy: { decidedAt: "asc" } }) : [],
    prisma.template.findUnique({ where: { id: guide.templateId } }),
  ]);
  const owner = isOwnerOrAdmin(ctx, guide);
  const canSeeAudit = hasRole(ctx, "AUDITOR", "ADMIN", "PUBLISHER") || owner;
  const audit = canSeeAudit ? await prisma.auditEvent.findMany({ where: { orgId: ctx.orgId, guideId: guide.id }, orderBy: { seq: "desc" }, take: 60 }) : [];
  const feedback = owner || hasRole(ctx, "AUDITOR", "PUBLISHER") ? await listFeedback(ctx, guide.id) : [];
  const isContrib = !!working && (working.authorId === ctx.userId || working.contributorIds.includes(ctx.userId));
  const st = working?.status;
  const perms: Perm = {
    submit: !!working && (st === "DRAFT" || st === "CHANGES_REQUESTED") && (canEditContent(ctx, guide) || owner),
    review: st === "IN_REVIEW" && hasRole(ctx, "REVIEWER") && !isContrib,
    approve: st === "READY_FOR_APPROVAL" && hasRole(ctx, "APPROVER") && !isContrib,
    publish: st === "APPROVED" && hasRole(ctx, "PUBLISHER") && working?.authorId !== ctx.userId,
    discard: st === "DRAFT" && canEditContent(ctx, guide),
    revise: !working && !!live && (canEditContent(ctx, guide) || owner),
    urgent: !working && !!live && hasRole(ctx, "PUBLISHER", "ADMIN"),
    underReview: owner || hasRole(ctx, "PUBLISHER"),
    completeReview: owner && !working,
    archive: hasRole(ctx, "PUBLISHER", "ADMIN"),
  };
  const authors = users.filter((u) => u.roles.includes("AUTHOR") && u.id !== ctx.userId).map((u) => ({ id: u.id, name: u.name }));
  return (
    <>
      <PageHead title={guide.title} sub={<>{guide.documentId} · {tpl?.name} · Owner: {users.find((u) => u.id === guide.ownerId)?.name ?? "unassigned"}</>}>
        {live ? <Link className="btn" href={`/g/${guide.documentId}`}>View live guide</Link> : null}
        {workingD ? <Link className="btn btn-primary" href={`/guides/${guide.id}/edit?v=${workingD.id}`}>{workingD.canEdit ? "Edit" : "Open"} working version</Link> : null}
      </PageHead>
      {guide.orphanedSince ? <p className="alert danger" role="alert"><strong>Orphaned guide.</strong> The process owner is inactive or missing since {fmtDate(guide.orphanedSince)}. Reassign ownership below.</p> : null}
      {recs.length ? (
        <section className="card" aria-labelledby="rc-h" style={{ marginBottom: 16 }}><h2 id="rc-h">Review recommendations</h2>
          <p className="muted">Generated by health checks. They never change approved content; accepting one marks the guide “under review” so the owner can decide what to do.</p>
          <ul>{recs.map((r) => <li key={r.id}><strong>{r.source.replaceAll("_", " ").toLowerCase()}</strong>: {(r.reasons as { message: string }[]).map((x) => x.message).join("; ")} {isOwnerOrAdmin(ctx, guide) || hasRole(ctx, "PUBLISHER") ? <RecommendationActions id={r.id} /> : null}</li>)}</ul>
        </section>
      ) : null}
      <div className="grid cols-2">
        <WorkflowActions guideId={guide.id} workingId={working?.id ?? null} workingStatus={working?.status ?? null} liveId={live?.id ?? null} liveStatus={live?.status ?? null} perms={perms} authors={authors} />
        <section className="card" aria-labelledby="hl-h">
          <h2 id="hl-h">Content health</h2>
          <p role="status"><strong>{assessment.level === "healthy" ? "Healthy" : assessment.level === "attention" ? "Needs attention" : "Blocked"}</strong>: {assessment.summary}</p>
          {findings.length === 0 ? <p className="muted">No findings.</p> : (
            <ul style={{ listStyle: "none", padding: 0, display: "grid", gap: 8 }}>
              {findings.map((f) => (
                <li key={f.id}><SeverityBadge severity={f.effectiveSeverity} /> {f.message}
                  <details><summary className="muted">Why is this flagged?</summary><p className="muted">{f.explanation}{f.exceptionReason ? ` Exception reason: ${f.exceptionReason}` : ""}</p></details>
                  {(hasRole(ctx, "PROCESS_OWNER", "APPROVER", "ADMIN") && (f.effectiveSeverity === "BLOCKING_ERROR" || f.effectiveSeverity === "ACCEPTED_EXCEPTION")) ? <FindingActions findingId={f.id} accepted={f.effectiveSeverity === "ACCEPTED_EXCEPTION"} /> : null}
                </li>
              ))}
            </ul>
          )}
          <p className="muted">Health checks explain themselves and never rewrite, withdraw or republish approved content.</p>
        </section>
      </div>

      <div style={{ marginTop: 16 }}>
        <MetadataForm canEdit={owner || canEditContent(ctx, guide)} canGovern={owner || (hasRole(ctx, "AUTHOR") && !guide.liveVersionId)}
          guide={{ id: guide.id, ownerId: guide.ownerId, backupOwnerId: guide.backupOwnerId, escalationUserId: guide.escalationUserId, escalationPath: guide.escalationPath, reviewFrequencyDays: guide.reviewFrequencyDays, siteId: guide.siteId, classification: guide.classification, criticality: guide.criticality, processCode: guide.processCode, functionCode: guide.functionCode, businessUnit: guide.businessUnit, department: guide.department, systems: guide.systems, applications: guide.applications, websites: guide.websites, urlPatterns: guide.urlPatterns, sapTransactions: guide.sapTransactions, businessRoles: guide.businessRoles, categories: guide.categories, workflowId: guide.workflowId }}
          users={users.map((u) => ({ id: u.id, name: u.name }))} sites={sites.map((s) => ({ id: s.id, name: s.name }))} workflows={workflows.map((w) => ({ id: w.id, name: w.name }))} />
      </div>

      <div className="grid cols-2" style={{ marginTop: 16 }}>
        <section className="card" aria-labelledby="vh-h"><h2 id="vh-h">Version history</h2>
          <div className="table-wrap"><table className="table"><thead><tr><th scope="col">Version</th><th scope="col">Status</th><th scope="col">Published</th><th scope="col">Summary</th></tr></thead><tbody>
            {versions.map((v) => <tr key={v.id}><td><Link href={`/g/${guide.documentId}/v/${v.number}`}>{v.label}</Link>{v.urgent ? " ⚡" : ""}</td><td><StatusBadge status={v.status} /></td><td>{fmtDate(v.publishedAt)}</td><td>{v.revisionSummary || "—"}</td></tr>)}
          </tbody></table></div>
          <div style={{ marginTop: 8 }}><CompareForm guideId={guide.id} versions={versions.map((v) => ({ id: v.id, label: v.label }))} /></div>
        </section>
        <section className="card" aria-labelledby="ap-h"><h2 id="ap-h">Approval history (current submission)</h2>
          {decisions.length === 0 ? <p className="muted">No decisions recorded on the working version.</p> : (
            <div className="table-wrap"><table className="table"><thead><tr><th scope="col">Phase</th><th scope="col">Person</th><th scope="col">Decision</th><th scope="col">When</th><th scope="col">Comment</th></tr></thead><tbody>
              {decisions.map((d) => <tr key={d.id}><td>{d.phase.toLowerCase()} {d.stageName ? `· ${d.stageName}` : ""}</td><td>{d.userName}</td><td>{d.decision.replace("_", " ").toLowerCase()}</td><td>{fmtDateTime(d.decidedAt)}</td><td>{d.comment || "—"}</td></tr>)}
            </tbody></table></div>
          )}
          {live?.controlSnapshot ? <p className="muted">Live version approvals: {((live.controlSnapshot as { approvals: { by: string; stage: string }[] }).approvals ?? []).map((a) => `${a.by} (${a.stage})`).join(", ")}</p> : null}
        </section>
      </div>

      {live && !working && (canEditContent(ctx, guide) || owner) ? <div style={{ marginTop: 16 }}><ReconcileForm guideId={guide.id} /></div> : null}
      {live ? (
        <section className="card" style={{ marginTop: 16 }} aria-labelledby="ln-h"><h2 id="ln-h">Links &amp; distribution</h2>
          <p>Permanent link: <a href={`/g/${guide.documentId}`}>{liveUrl(guide.documentId)}</a> · Short link: <code>/s/{guide.shortCode}</code> · Embed: <code>/embed/g/{guide.documentId}</code></p>
        </section>
      ) : null}

      {feedback.length ? (
        <section className="card" style={{ marginTop: 16 }} aria-labelledby="fb-h"><h2 id="fb-h">Feedback and outdated-content reports</h2>
          <p className="muted">Reports are about the guide. Submitter identity is not shown.</p>
          <div className="table-wrap"><table className="table"><thead><tr><th scope="col">Type</th><th scope="col">Rating</th><th scope="col">Comment</th><th scope="col">Status</th><th scope="col">Date</th><th scope="col"><span className="visually-hidden">Actions</span></th></tr></thead><tbody>
            {feedback.map((f) => <tr key={f.id}><td>{f.kind.toLowerCase()}</td><td>{f.rating ?? "—"}</td><td>{f.comment || "—"}</td><td>{f.status.toLowerCase()}</td><td>{fmtDate(f.createdAt)}</td><td>{owner && f.status !== "RESOLVED" ? <FeedbackActions guideId={guide.id} id={f.id} /> : null}</td></tr>)}
          </tbody></table></div>
        </section>
      ) : null}

      {canSeeAudit ? (
        <section className="card" style={{ marginTop: 16 }} aria-labelledby="au-h"><h2 id="au-h">Audit trail</h2>
          <div className="table-wrap"><table className="table"><thead><tr><th scope="col">When</th><th scope="col">Who</th><th scope="col">Event</th></tr></thead><tbody>
            {audit.map((a) => <tr key={a.id}><td>{fmtDateTime(a.at)}</td><td>{a.actorLabel}</td><td>{a.summary}</td></tr>)}
          </tbody></table></div>
        </section>
      ) : null}
    </>
  );
}
